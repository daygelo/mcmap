// Regenerates supabase/seed.sql from the in-app club catalog so group slugs
// match the app's club ids. Run from the repo root:
//   dart run tool/generate_seed.dart > supabase/seed.sql
import 'package:mcmap/data/campus_groups.dart';
import 'package:mcmap/data/clubs.dart';

String q(String? value) =>
    value == null ? 'null' : "'${value.replaceAll("'", "''")}'";

/// A short acronym-style alias ("SSMU", "EUS JC").
String? shortNameFor(ClubOrganization club) =>
    club.aliases.where((alias) => alias.length <= 12).firstOrNull;

/// Existing rows are refreshed, but text edited in the dashboard is kept.
const _onConflict = '''
on conflict (slug) do update set
  name = excluded.name,
  type = excluded.type,
  category = excluded.category,
  short_name = coalesce(groups.short_name, excluded.short_name),
  website_url = coalesce(groups.website_url, excluded.website_url)''';

void main() {
  final out = StringBuffer()
    ..writeln('-- Groups and sample events for development and demos.')
    ..writeln('-- GENERATED by tool/generate_seed.dart from the in-app club')
    ..writeln('-- catalog and lib/data/campus_groups.dart. Edit those, then:')
    ..writeln('--   dart run tool/generate_seed.dart > supabase/seed.sql')
    ..writeln('-- Run every migration first. Safe to run more than once.')
    ..writeln()
    ..writeln(
      '-- Catalog clubs, societies, design teams and first-year groups.',
    )
    ..writeln(
      'insert into public.groups '
      '(slug, name, short_name, type, category, website_url) values',
    )
    ..writeln(
      [
        for (final club in clubCatalog)
          '  (${q(club.id)}, ${q(club.name)}, ${q(shortNameFor(club))}, '
              '${q(club.type.dbValue)}, ${q(club.category)}, '
              '${q(club.sourceUrls.first)})',
      ].join(',\n'),
    )
    ..writeln('$_onConflict;')
    ..writeln()
    ..writeln('-- Other campus groups. metadata.verified is false where no')
    ..writeln('-- public page confirming the group was found.')
    ..writeln(
      'insert into public.groups (slug, name, short_name, handle, type, '
      'category, faculty_affiliation, description, website_url, metadata) '
      'values',
    )
    ..writeln(
      [
        for (final group in campusGroups)
          '  (${q(group.id)}, ${q(group.name)}, ${q(group.shortName)}, '
              '${q(group.handle)}, ${q(group.type!.dbValue)}, '
              '${q(group.type!.label)}, ${q(group.facultyAffiliation)}, '
              '${q(group.description)}, ${q(group.sourceUrl)}, '
              '\'{"verified": ${group.sourceUrl != null}}\')',
      ].join(',\n'),
    )
    ..writeln('$_onConflict,')
    ..writeln('  handle = coalesce(groups.handle, excluded.handle),')
    ..writeln(
      '  faculty_affiliation = coalesce(groups.faculty_affiliation, '
      'excluded.faculty_affiliation),',
    )
    ..writeln(
      '  description = coalesce(groups.description, excluded.description),',
    )
    ..writeln('  metadata = excluded.metadata || groups.metadata;')
    ..writeln()
    ..write(_handWritten);
  // ignore: avoid_print
  print(out.toString().trimRight());
}

