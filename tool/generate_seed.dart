// Regenerates supabase/seed.sql from the in-app club catalog so group slugs
// match the app's club ids. Run from the repo root:
//   dart run tool/generate_seed.dart > supabase/seed.sql
import 'package:mcmap/data/clubs.dart';

String q(String? value) =>
    value == null ? 'null' : "'${value.replaceAll("'", "''")}'";

const _types = {
  OrganizationType.club: 'club',
  OrganizationType.designTeam: 'design_team',
  OrganizationType.studentSociety: 'society',
  OrganizationType.firstYearCouncil: 'first_year_council',
  OrganizationType.firstYearCommittee: 'first_year_committee',
  OrganizationType.firstYearSociety: 'first_year_society',
};

void main() {
  final out = StringBuffer()
    ..writeln('-- Seed data for local development and demos.')
    ..writeln('-- GENERATED by tool/generate_seed.dart (groups come from the')
    ..writeln('-- in-app club catalog). Edit the script, not this file.')
    ..writeln()
    ..writeln(
      '-- Catalog clubs, societies, design teams and first-year groups.',
    )
    ..writeln(
      'insert into public.groups (slug, name, type, category, website_url) values',
    );
  final rows = [
    for (final club in clubCatalog)
      '  (${q(club.id)}, ${q(club.name)}, \'${_types[club.type]}\', '
          '${q(club.category)}, ${q(club.sourceUrls.first)})',
  ];
  out
    ..writeln(rows.join(',\n'))
    ..writeln('on conflict (slug) do nothing;')
    ..writeln()
    ..write(_handWritten);
  // ignore: avoid_print
  print(out.toString().trimRight());
}

